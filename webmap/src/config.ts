// Raster (COG) collections served through TiTiler. Items are discovered from
// the STAC API at runtime; `titilerParams` controls styling and must stay in
// step with the `renders` metadata in pipelines/03-gold/catalog_silver.py.
export interface RasterDef {
  id: string; // == STAC collection id
  label: string;
  titilerParams: string; // extra query string for the tiler (no leading &)
  description: string; // one-line plain-language summary
  legend?: Legend;
  // Per-acquisition-date collections (true) render one date at a time (mosaic
  // if present, per-item COGs otherwise). Date-independent collections (false,
  // e.g. annual LULC) render all their COGs at once.
  temporal: boolean;
}

